    private void btnDodajStavkuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajStavkuActionPerformed

        Usluga usluga = (Usluga) cmbUsluga.getSelectedItem();
        double iznos = Double.parseDouble(txtIznos.getText());
        String napomena = txtNapomena.getText();

        StavkaRezervacije sr = new StavkaRezervacije(null, -1, napomena,
                usluga.getCena(), iznos, brojDana, usluga);

        ModelTabeleStavkeRezervacije mt = (ModelTabeleStavkeRezervacije) tblStavke.getModel();

        if (mt.postojiUsluga(usluga)) {
            JOptionPane.showMessageDialog(this, "Vec ste uneli ovu uslugu!");
            return;
        }

        mt.dodajStavku(sr);

        ukupanIznos = mt.vratiUkupanIznos() + cenaPoDanu * brojDana;
        lblUkupanIznos.setText(String.valueOf(ukupanIznos) + "din");
    }//GEN-LAST:event_btnDodajStavkuActionPerformed

    private void btnObrisiStavkuActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiStavkuActionPerformed

        int red = tblStavke.getSelectedRow();

        if (red >= 0) {
            ModelTabeleStavkeRezervacije mt = (ModelTabeleStavkeRezervacije) tblStavke.getModel();
            mt.obrisiStavku(red);

            ukupanIznos = mt.vratiUkupanIznos() + cenaPoDanu * brojDana;
            lblUkupanIznos.setText(String.valueOf(ukupanIznos) + "din");
        }
    }//GEN-LAST:event_btnObrisiStavkuActionPerformed

    private void btnSacuvajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSacuvajActionPerformed

        try {
            if (txtBrojDana.getText().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Morate izracunati broj dana!");
                return;
            }

            Gost gost = (Gost) cmbGost.getSelectedItem();
            String soba = (String) cmbSoba.getSelectedItem();
            SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");
            Date datumPrijave = sdf.parse(txtDatumPrijave.getText());
            Date datumOdjave = sdf.parse(txtDatumOdjave.getText());

            ModelTabeleStavkeRezervacije mt = (ModelTabeleStavkeRezervacije) tblStavke.getModel();

            Rezervacija r = new Rezervacija(-1, datumPrijave, datumOdjave, ukupanIznos,
                    soba, gost, ulogovani, mt.getLista());

            KlijentKontroler.getInstance().dodajRezervaciju(r);
            txtBrojDana.setText("");
            mt.getLista().clear();
            mt.fireTableDataChanged();
            cmbUsluga.setEnabled(false);
            btnObrisiStavku.setEnabled(false);
            btnDodajStavku.setEnabled(false);
            lblUkupanIznos.setText("0.00");
            txtIznos.setText("0.00");
            txtDatumPrijave.setText("");
            txtDatumOdjave.setText("");
            ukupanIznos = 0;
            brojDana = 0;
            JOptionPane.showMessageDialog(this, "Uspesno sacuvana rezervacija!");

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
            // Logger.getLogger(GlavnaForma.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnSacuvajActionPerformed

