    private void btnIzracunajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzracunajActionPerformed

        ModelTabeleStavkeRezervacije mt = (ModelTabeleStavkeRezervacije) tblStavke.getModel();
        mt.getLista().clear();
        mt.fireTableDataChanged();

        if (txtDatumPrijave.getText().isEmpty() || txtDatumOdjave.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Morate popuniti datum prijave i datum odjave!");
            return;
        }

        try {
            SimpleDateFormat sdf = new SimpleDateFormat("dd.MM.yyyy");
            Date datumPrijave = sdf.parse(txtDatumPrijave.getText());
            Date datumOdjave = sdf.parse(txtDatumOdjave.getText());

            if (datumPrijave.after(datumOdjave) || datumPrijave.equals(datumOdjave)) {
                JOptionPane.showMessageDialog(this, "Datum prijave mora biti pre datuma odjave!");
                return;
            }

            if (datumPrijave.before(new Date()) || datumPrijave.equals(datumOdjave)) {
                JOptionPane.showMessageDialog(this, "Datum prijave mora biti u buducnosti!");
                return;
            }

            long razlikaMilisekunde = datumOdjave.getTime() - datumPrijave.getTime();
            long razlika = TimeUnit.DAYS.convert(razlikaMilisekunde, TimeUnit.MILLISECONDS);

            txtBrojDana.setText(String.valueOf(razlika));

            brojDana = Integer.parseInt(txtBrojDana.getText());

            cmbUsluga.setEnabled(true);
            btnObrisiStavku.setEnabled(true);
            btnDodajStavku.setEnabled(true);
            
                
            cenaPoDanu = Double.parseDouble(txtCenaPoDanu.getText());

            ukupanIznos = cenaPoDanu * brojDana;

            lblUkupanIznos.setText(String.valueOf(ukupanIznos) + "din");

            Usluga usluga = (Usluga) cmbUsluga.getSelectedItem();
            if (!txtBrojDana.getText().isEmpty()) {
                txtIznos.setText(String.valueOf(usluga.getCena() * brojDana));
            }

        } catch (Exception ex) {
            Logger.getLogger(GlavnaForma.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_btnIzracunajActionPerformed

